def _parse(glyph_text: str, ascent: int, descent: int) -> Dict[str, List[str]]:
    glyphs = {}
    for line in glyph_text.strip("\n").splitlines():
        char, *rows = line.split(" ")
        assert len(char) == 1, line
        assert len(rows) in (ascent, ascent + descent), line
        assert len(set(len(x) for x in rows)) == 1, line
        glyphs[char] = rows + ["." * len(rows[0])] * (ascent + descent - len(rows))
    return glyphs


def _embolden(glyphs: Dict[str, List[str]]) -> Dict[str, List[str]]:
    """Thicken glyphs by OR-ing each one with itself shifted 1 pixel right."""
    return {
        char: ["".join("#" if "#" in (a, b) else "." for a, b in zip(x + ".", "." + x)) for x in rows]
        for char, rows in glyphs.items()
    }


class PixelFont:
    """A bitmap font drawn pixel by pixel, rendered without any scaling.

    >>> image = BUILTIN_FONTS["tiny"].render("Hi")
    >>> image.size
    (7, 5)
    >>> print("\\n".join("".join("#" if image.getpixel((x, y)) else "."
    ...                          for x in range(image.width)) for y in range(image.height)))
    #.#.###
    #.#..#.
    ###..#.
    #.#..#.
    #.#.###
    """

    def __init__(self, glyphs: Dict[str, List[str]], ascent: int, descent: int,
                 space_width: int, uppercase_only: bool = False, spacing: int = 1):
        self.glyphs = glyphs
        self.height = ascent + descent
        self.glyphs[" "] = ["." * space_width] * self.height
        self.uppercase_only = uppercase_only
        self.spacing = spacing

    def _glyph(self, char: str) -> List[str]:
        if self.uppercase_only:
            char = char.upper()
        if char not in self.glyphs:
            logger.warning("Character %r is not in the built-in font and is shown as '?'.", char)
            char = "?"
        return self.glyphs[char]

    def render(self, text: str) -> Image.Image:
        glyph_list = [self._glyph(x) for x in text]
        width = sum(len(x[0]) for x in glyph_list) + self.spacing * max(len(glyph_list) - 1, 0)
        image = Image.new("L", (max(width, 1), self.height))
        left = 0
        for rows in glyph_list:
            for y, row in enumerate(rows):
                for x, pixel in enumerate(row):
                    if pixel == "#":
                        image.putpixel((left + x, y), 255)
            left += len(rows[0]) + self.spacing
        return image


_PIXEL_GLYPHS = _parse(_PIXEL, ascent=7, descent=2)

BUILTIN_FONTS = {
    "pixel": PixelFont(_PIXEL_GLYPHS, ascent=7, descent=2, space_width=3),
    "bold": PixelFont(_embolden(_PIXEL_GLYPHS), ascent=7, descent=2, space_width=3),
    "tiny": PixelFont(_parse(_TINY, ascent=5, descent=0), ascent=5, descent=0,
                      space_width=2, uppercase_only=True),
}
